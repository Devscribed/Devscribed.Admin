    // TC-09-INT-06: Approve request — happy path
    [Fact]
    public async Task Approve_request_creates_debit_and_updates_balance()
    {
        var org = NewOrg("Acme Inc");
        await SeedMemberAsync(org, "admin06@acme.com", "Passw0rd", role: "admin");
        var (_, user) = await SeedMemberAsync(org, "user06@acme.com", "Passw0rd", role: "user");
        await SetFinancialsAsync(user.Id, MonthlySalaryFor10Days);
        await AddCreditAsync(user.Id, 5000m);
