    // TC-09-INT-10: Cancel approved request — by manager (refund)
    [Fact]
    public async Task Cancel_approved_request_by_manager_creates_refund()
    {
        var org = NewOrg("Acme Inc");
        var (_, manager) = await SeedMemberAsync(org, "manager10@acme.com", "Passw0rd", role: "manager");
        var (_, user) = await SeedMemberAsync(org, "user10@acme.com", "Passw0rd", role: "user");
        await SetFinancialsAsync(user.Id, MonthlySalaryFor10Days);
        await AddCreditAsync(user.Id, 5000m);
        var request = await SeedRequestAsync(user.Id, FutureMonday(3), FutureMonday(3).AddDays(4), 5, 692.31m, VacationRequestStatuses.Approved);
        await AddDebitAsync(user.Id, request.Id, 692.31m); // simulate the debit that a real approval would have posted

        var client = await LoggedInClientAsync("manager10@acme.com", "Passw0rd");
        var response = await client.PutAsync($"/api/organizations/{org.Id}/members/{user.Id}/vacation/requests/{request.Id}/cancel", null);

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var body = (await response.Content.ReadFromJsonAsync<JsonDocument>())!.RootElement;
        Assert.True(body.GetProperty("refunded").GetBoolean());
        Assert.Equal(692.31m, body.GetProperty("refundAmount").GetDecimal());

        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var reloaded = await db.VacationRequests.SingleAsync(r => r.Id == request.Id);
        Assert.Equal(VacationRequestStatuses.Cancelled, reloaded.Status);
        var refund = await db.VacationReserveTransactions.SingleAsync(t => t.VacationRequestId == request.Id && t.Type == "refund");
        Assert.Equal(692.31m, refund.Amount);

        var reserveBalance = await db.VacationReserveTransactions.Where(t => t.MembershipId == user.Id).SumAsync(t => t.Amount);
        Assert.Equal(5000m, reserveBalance); // credit 5000 - debit 692.31 + refund 692.31
    }

