    private async Task<(Account Account, Membership Membership)> SeedMemberAsync(
        Organization org, string email, string password, string role = "user", string status = "active",
        string firstName = "Pat", string lastName = "Owner")
    {
        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var hasher = scope.ServiceProvider.GetRequiredService<IPasswordHasher>();

        if (!db.Organizations.Any(o => o.Id == org.Id))
            db.Organizations.Add(org);

        var account = new Account
        {
            Id = Guid.NewGuid(),
            Email = email,
            PasswordHash = hasher.Hash(password),
            FirstName = firstName,
            LastName = lastName,
            CreatedAt = DateTime.UtcNow,
        };
        var membership = new Membership
        {
            Id = Guid.NewGuid(),
            AccountId = account.Id,
            OrganizationId = org.Id,
            Role = role,
            Status = status,
            JoinedAt = DateTime.UtcNow,
        };
        db.Accounts.Add(account);
        db.Memberships.Add(membership);
        await db.SaveChangesAsync();
        return (account, membership);
    }

    private static Organization NewOrg(string name) => new() { Id = Guid.NewGuid(), Name = name, CreatedAt = DateTime.UtcNow };

    private async Task<HttpClient> LoggedInClientAsync(string email, string password)
    {
        var client = _factory.CreateClient();
        var response = await client.PostAsJsonAsync("/api/login", new { email, password });
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        return client;
    }

    private async Task SetFinancialsAsync(Guid membershipId, decimal monthlySalary, int vacationDaysPerYear = 20)
    {
        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        db.MemberFinancials.Add(new MemberFinancials
        {
            Id = Guid.NewGuid(),
            MembershipId = membershipId,
            MonthlySalary = monthlySalary,
            ClientHourlyRate = 40m,
            VacationDaysPerYear = vacationDaysPerYear,
            Currency = "USD",
            VacationReservePercent = 3.33m,
            UpdatedAt = DateTime.UtcNow,
        });
        await db.SaveChangesAsync();
    }

    private async Task AddCreditAsync(Guid membershipId, decimal amount)
    {
        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var ledger = scope.ServiceProvider.GetRequiredService<VacationLedgerService>();
        ledger.PostTransaction(membershipId, VacationTransactionTypes.Credit, amount, "seed credit", isAutoGenerated: true);
        await db.SaveChangesAsync();
    }

    private async Task AddDebitAsync(Guid membershipId, Guid requestId, decimal amount)
    {
        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var ledger = scope.ServiceProvider.GetRequiredService<VacationLedgerService>();
        ledger.PostTransaction(membershipId, VacationTransactionTypes.Debit, -amount, "seed debit", isAutoGenerated: false, vacationRequestId: requestId);
        await db.SaveChangesAsync();
    }

    private async Task<VacationRequest> SeedRequestAsync(
        Guid membershipId, DateOnly start, DateOnly end, int workingDays, decimal deductionAmount, string status)
    {
        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var request = new VacationRequest
        {
            Id = Guid.NewGuid(),
            MembershipId = membershipId,
            StartDate = start,
            EndDate = end,
            WorkingDays = workingDays,
            DeductionAmount = deductionAmount,
            Status = status,
            RequestedAt = DateTime.UtcNow,
        };
        if (status == VacationRequestStatuses.Approved)
        {
            request.ReviewedAt = DateTime.UtcNow;
        }
        db.VacationRequests.Add(request);
        await db.SaveChangesAsync();
        return request;
    }

    // dailySalary for monthlySalary=3000 is 3000*12/260 = 138.4615...
    private const decimal MonthlySalaryFor10Days = 3000m;

    // Returns a future Monday (so Monday..+4 days is always exactly 5 weekdays), offset by whole weeks
    // so test date ranges never overlap with each other and are always relative to "today" regardless of
    // when the suite runs.
    private static DateOnly FutureMonday(int weeksAhead)
    {
        var today = DateTime.UtcNow.Date;
        var daysUntilMonday = ((int)DayOfWeek.Monday - (int)today.DayOfWeek + 7) % 7;
        if (daysUntilMonday == 0) daysUntilMonday = 7;
        return DateOnly.FromDateTime(today.AddDays(daysUntilMonday + weeksAhead * 7));
    }

    // TC-09-INT-01: Submit vacation request — happy path
    [Fact]
    public async Task Submit_request_happy_path_reduces_available_days()
    {
        var org = NewOrg("Acme Inc");
        var (_, user) = await SeedMemberAsync(org, "user01@acme.com", "Passw0rd", role: "user");
        await SetFinancialsAsync(user.Id, MonthlySalaryFor10Days);
        await AddCreditAsync(user.Id, 1384.62m); // ~10 days worth

        var start = FutureMonday(1);
        var client = await LoggedInClientAsync("user01@acme.com", "Passw0rd");
        var response = await client.PostAsJsonAsync($"/api/organizations/{org.Id}/members/{user.Id}/vacation/requests",
            new { startDate = start.ToString("yyyy-MM-dd"), endDate = start.AddDays(4).ToString("yyyy-MM-dd") });

        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        var body = (await response.Content.ReadFromJsonAsync<JsonDocument>())!.RootElement;
        Assert.Equal(5, body.GetProperty("workingDays").GetInt32());
        Assert.Equal("pending", body.GetProperty("status").GetString());

        var getResponse = await client.GetAsync($"/api/organizations/{org.Id}/members/{user.Id}/vacation");
        var getBody = (await getResponse.Content.ReadFromJsonAsync<JsonDocument>())!.RootElement;
        Assert.Equal(5, getBody.GetProperty("balance").GetProperty("pendingDays").GetInt32());
    }

