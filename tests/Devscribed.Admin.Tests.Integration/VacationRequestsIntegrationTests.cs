    // TC-09-INT-12: Concurrent approval race condition
    [Fact]
    public async Task Concurrent_approvals_only_one_succeeds()
    {
        var org = NewOrg("Acme Inc");
        var (_, admin) = await SeedMemberAsync(org, "admin12@acme.com", "Passw0rd", role: "admin");
        var (_, manager) = await SeedMemberAsync(org, "manager12@acme.com", "Passw0rd", role: "manager");
        var (_, user) = await SeedMemberAsync(org, "user12@acme.com", "Passw0rd", role: "user");
        await SetFinancialsAsync(user.Id, MonthlySalaryFor10Days);
        await AddCreditAsync(user.Id, 692.31m); // exactly ~5 days worth (matches one request)

        var r1 = await SeedRequestAsync(user.Id, FutureMonday(1), FutureMonday(1).AddDays(4), 5, 692.31m, VacationRequestStatuses.Pending);
        var r2 = await SeedRequestAsync(user.Id, FutureMonday(2), FutureMonday(2).AddDays(4), 5, 692.31m, VacationRequestStatuses.Pending);

        var adminClient = await LoggedInClientAsync("admin12@acme.com", "Passw0rd");
        var managerClient = await LoggedInClientAsync("manager12@acme.com", "Passw0rd");

        var task1 = adminClient.PutAsJsonAsync($"/api/organizations/{org.Id}/members/{user.Id}/vacation/requests/{r1.Id}/review", new { decision = "approved" });
        var task2 = managerClient.PutAsJsonAsync($"/api/organizations/{org.Id}/members/{user.Id}/vacation/requests/{r2.Id}/review", new { decision = "approved" });

        var results = await Task.WhenAll(task1, task2);

        var successCount = results.Count(r => r.StatusCode == HttpStatusCode.OK);
        var failureCount = results.Count(r => r.StatusCode == HttpStatusCode.BadRequest);

        Assert.Equal(1, successCount);
        Assert.Equal(1, failureCount);

        var failedResponse = results.First(r => r.StatusCode == HttpStatusCode.BadRequest);
        var failedBody = (await failedResponse.Content.ReadFromJsonAsync<JsonDocument>())!.RootElement;
        Assert.Equal("insufficient_balance", failedBody.GetProperty("error").GetString());

        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var debitCount = await db.VacationReserveTransactions.CountAsync(t => t.MembershipId == user.Id && t.Type == "debit");
        Assert.Equal(1, debitCount);
    }

    // TC-09-INT-13: Member removal auto-cancels pending requests
    [Fact]
    public async Task Removing_member_cancels_pending_and_future_approved_requests()
    {
        var org = NewOrg("Acme Inc");
        await SeedMemberAsync(org, "admin13@acme.com", "Passw0rd", role: "admin");
        var (_, user) = await SeedMemberAsync(org, "user13@acme.com", "Passw0rd", role: "user");
        await SetFinancialsAsync(user.Id, MonthlySalaryFor10Days);
        await AddCreditAsync(user.Id, 5000m);

        var futureDate = DateTime.UtcNow.AddMonths(2);
        var r1 = await SeedRequestAsync(user.Id, FutureMonday(1), FutureMonday(1).AddDays(4), 5, 692.31m, VacationRequestStatuses.Pending);
        var r2 = await SeedRequestAsync(user.Id, DateOnly.FromDateTime(futureDate), DateOnly.FromDateTime(futureDate.AddDays(4)), 5, 692.31m, VacationRequestStatuses.Approved);

        var client = await LoggedInClientAsync("admin13@acme.com", "Passw0rd");
        var response = await client.DeleteAsync($"/api/organizations/{org.Id}/members/{user.Id}");
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        using var scope = _factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var reloadedR1 = await db.VacationRequests.SingleAsync(r => r.Id == r1.Id);
        var reloadedR2 = await db.VacationRequests.SingleAsync(r => r.Id == r2.Id);

        Assert.Equal(VacationRequestStatuses.Cancelled, reloadedR1.Status);
        Assert.Equal(VacationRequestStatuses.Cancelled, reloadedR2.Status);
        var refund = await db.VacationReserveTransactions.SingleOrDefaultAsync(t => t.VacationRequestId == r2.Id && t.Type == "refund");
        Assert.NotNull(refund);
        Assert.Equal(692.31m, refund!.Amount);
        Assert.False(await db.VacationReserveTransactions.AnyAsync(t => t.VacationRequestId == r1.Id));
    }
