    // TC-10-E2E-04: Requests page — cancel approved request
    [Test]
    public async Task Manager_cancels_approved_request_from_requests_page()
    {
        _server.SeedAccount("admin-e2e-orgreq4@acme.com", "Passw0rd", orgName: "Acme Inc", role: "admin");
        var orgId = GetOrgId("admin-e2e-orgreq4@acme.com");
        SeedAdditionalMember(orgId, "manager-e2e-orgreq4@acme.com", "Passw0rd", "manager", "Man", "Ager");
        SeedAdditionalMember(orgId, "alex-e2e-orgreq4@acme.com", "Passw0rd", "user", "Alex", "Four");
        var memberId = GetMembershipId("alex-e2e-orgreq4@acme.com");
        ConfigureFinancialsAndCredit(memberId, 3000, 5000m);

        var start = FutureMonday(1);
        var request = SeedRequest(memberId, start, start.AddDays(4), 5, 692.31m, VacationRequestStatuses.Approved);
        SeedDebit(memberId, request.Id, 692.31m);

        await LoginAsync("manager-e2e-orgreq4@acme.com", "Passw0rd");
        await Page.GotoAsync($"{_server.BaseUrl}/org/{orgId}/requests");
        await Page.GetByTestId("requests-status-filter").SelectOptionAsync("all");

        Page.Dialog += async (_, dialog) => await dialog.AcceptAsync();
        await Page.GetByTestId($"requests-card-cancel-{request.Id}").ClickAsync();

        await Expect(Page.GetByTestId("toast-request-cancelled")).ToBeVisibleAsync();
        await Expect(Page.GetByTestId("toast-request-cancelled")).ToContainTextAsync("reserve refunded");
        await Expect(Page.GetByTestId($"requests-card-status-{request.Id}")).ToContainTextAsync("Cancelled");
    }
}
