        _server.SeedAccount("admin-e2e-req4@acme.com", "Passw0rd", orgName: "Acme Inc", role: "admin");
        var orgId = GetOrgId("admin-e2e-req4@acme.com");
        SeedAdditionalMember(orgId, "manager-e2e-req4@acme.com", "Passw0rd", "manager", "Man", "Ager");
