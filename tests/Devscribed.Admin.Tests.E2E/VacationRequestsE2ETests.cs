        await Expect(Page.GetByTestId("toast-request-cancelled")).ToBeVisibleAsync();
        await Expect(Page.GetByTestId("toast-request-cancelled")).ToContainTextAsync("reserve refunded");
        await Expect(Page.GetByTestId($"vacation-request-status-{request.Id}")).ToContainTextAsync("Cancelled");
        await Expect(Page.GetByTestId("vacation-reserve-amount")).ToContainTextAsync("5000.00");
        await Expect(Page.GetByTestId("vacation-transactions-table")).ToContainTextAsync("Refund");
    }

    // TC-09-E2E-05: Insufficient balance blocks request submission
    [Test]
    public async Task Insufficient_balance_blocks_request_submission()
    {
        _server.SeedAccount("admin-e2e-req5@acme.com", "Passw0rd", orgName: "Acme Inc", role: "admin");
        var orgId = GetOrgId("admin-e2e-req5@acme.com");
