        var memberId = GetMembershipId("alex-e2e-req5@acme.com");
        ConfigureFinancialsAndCredit(memberId, 3000, 276.93m); // ~2 available days

        var start = FutureMonday(1);

        await LoginAsync("alex-e2e-req5@acme.com", "Passw0rd");
